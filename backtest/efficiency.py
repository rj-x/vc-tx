import argparse
import json
import os
import subprocess
import sys

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

from backtest.sessions import sessions_of_index

OUT = os.path.join(ROOT, "reports", "scoreboard")
EFF_WINDOW_BARS = 15    # one signal-TF window (15M) in 1M bars


def eff15(closes, window=EFF_WINDOW_BARS):
    """Trailing-window efficiency ratio per bar (NaN until the window
    fills or when the path is zero)."""
    c = np.asarray(closes, float)
    steps = np.abs(np.diff(c, prepend=c[0]))
    cpath = np.cumsum(steps)
    out = np.full(len(c), np.nan)
    net = np.abs(c[window:] - c[:-window])
    path = cpath[window:] - cpath[:-window]
    with np.errstate(invalid="ignore", divide="ignore"):
        out[window:] = np.where(path > 0, net / path, np.nan)
    return out


def eff_session(closes, ts):
    """Session-to-date efficiency ratio (UTC-day reset, stated)."""
    c = np.asarray(closes, float)
    days = np.asarray(ts, "int64") // 86_400_000_000_000
    out = np.full(len(c), np.nan)
    anchor = 0
    path = 0.0
    prev = None
    for i in range(len(c)):
        if days[i] != prev:
            anchor, path, prev = i, 0.0, days[i]
        if i > anchor:
            path += abs(c[i] - c[i - 1])
            if path > 0:
                out[i] = abs(c[i] - c[anchor]) / path
    return out


def _dist(v):
    v = v[~np.isnan(v)]
    if not len(v):
        return None
    return {"n": int(len(v)),
            "median": round(float(np.median(v)), 3),
            "p10": round(float(np.percentile(v, 10)), 3),
            "p90": round(float(np.percentile(v, 90)), 3)}


def run_instrument(instr, boundary_ns, golive_ns):
    df = pd.read_csv(os.path.join(ROOT, "clean_finsa",
                                  f"{instr}_1min.csv"),
                     usecols=["time", "close"], parse_dates=["time"])
    ts = df["time"].astype("int64").to_numpy()
    e15 = eff15(df["close"].to_numpy())
    esess = eff_session(df["close"].to_numpy(), ts)
    sess = np.array(sessions_of_index(
        pd.DatetimeIndex(df["time"])), dtype=object)
    wmask = {"backtest": ts < boundary_ns, "forward": ts >= golive_ns}
    out = {"instrument": instr, "n_bars": int(len(ts)), "cells": {},
           "eff15_store_median": round(float(np.nanmedian(e15)), 3)}
    for w, m in wmask.items():
        for s in sorted(set(sess.tolist())):
            sel = m & (sess == s)
            out["cells"][f"{w}|{s}"] = {"eff15": _dist(e15[sel]),
                                        "eff_sess": _dist(esess[sel])}
    return out


def _emit(art, head):
    L = ["# Organ #2 (regime/efficiency half) — Efficiency Ratio "
         "(GENERATED by backtest.efficiency)", "",
         "Terms: [docs/GLOSSARY.md](../../docs/GLOSSARY.md).", "",
         f"Engine `{head[:9]}` — OBSERVATIONAL ORGAN (register 122; "
         "prereg_organ_efficiency; register-16 family; the built half "
         "is the register-95 deceleration class). VOCABULARY, not a "
         "signal: efficiency ratio = |net move| / path length over the "
         f"trailing {EFF_WINDOW_BARS} x 1M bars (eff15) and the UTC "
         "trading day to date (eff_sess, day convention FLAGGED). A "
         "SECOND LENS beside the 1M phase tracker, never a "
         "replacement. Customers: the capture study's "
         "efficiency-at-entry split (cut at the store's own median — "
         "parameter-free), the per-market track (future). Consumers "
         "price their own fields.", ""]
    for res in art["results"]:
        L += [f"## {res['instrument']} ({res['n_bars']} 1M bars; eff15 "
              f"store median {res['eff15_store_median']})", "",
              "| window | session | eff15 med [p10..p90] | eff_sess med "
              "[p10..p90] | n |", "|---|---|---|---|---|"]
        for key, c in res["cells"].items():
            w, s = key.split("|")
            a, b = c["eff15"], c["eff_sess"]
            if not a or not b:
                continue
            L.append(f"| {w} | {s} | {a['median']} [{a['p10']}"
                     f"..{a['p90']}] | {b['median']} [{b['p10']}"
                     f"..{b['p90']}] | {a['n']} |")
        L.append("")
    with open(os.path.join(OUT, "efficiency.md"), "w") as f:
        f.write("\n".join(L))


def main():
    from engine.store_loader import lockbox_boundary, zones
    ap = argparse.ArgumentParser()
    ap.add_argument("--instr", nargs="*",
                    default=["uk100fut", "ger40fut", "nas100fut",
                             "us30fut"])
    a = ap.parse_args()
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT,
                          capture_output=True, text=True).stdout.strip()
    b, g = lockbox_boundary().value, zones()["go_live"].value
    results = [run_instrument(i, b, g) for i in a.instr]
    art = {"STAMP": ("OBSERVATIONAL organ #2 regime/efficiency half — "
                     "vocabulary; a second lens beside the phase "
                     "tracker; never validation"),
           "engine_commit": head, "window_bars": EFF_WINDOW_BARS,
           "results": results}
    with open(os.path.join(OUT, "efficiency.json"), "w") as f:
        json.dump(art, f, indent=2, default=str)
    _emit(art, head)
    print(f"OBSERVATIONAL organ #2-half -> {OUT}/efficiency.md")


if __name__ == "__main__":
    main()
