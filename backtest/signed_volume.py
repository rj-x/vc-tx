"""Organ #4 — cumulative signed volume (register 119; pre-registered
prereg_organ_signed_volume, counted 2026-08-31; register-16 organ,
build ordered by the 2026-08-31 session order item 3; dispositions
register 115). OBSERVATIONAL VOCABULARY — an organ is a per-bar field,
never a signal: no signal, question or recipe changes from this build.

THE FIELDS (close-direction signed volume; every unit registered or
the calendar's own):
- sv_bar   = sign(close - open) x volume (doji bars sign 0);
- sv15     = the trailing one-signal-TF window sum (15 x 1M bars —
             the stack's registered signal TF as the window unit);
- sv_sess  = the session-to-date running sum, reset at each new UTC
             trading day (the capture study's day convention reused;
             the store-native ldate session is the alternative —
             implementer choice, FLAGGED).

CUSTOMERS (named at registration): H12's clauses — the "absorber's
direction" needs a sign source and its vocabulary was never built
(register 115: zero fires everywhere); the conditioning matrix (the
sv_sess sign joins as a dimension — field size restated in the matrix
header); arrival-anatomy metrics (a)/(b) (signed-volume medians in the
zone's favor). H12's re-registration itself stays a FUTURE OPERATOR
PROPOSAL — nothing here changes a signal.

THE ARTIFACT: per leg x session x window, bar-level distributions of
sv15 and sv_sess (median / p10 / p90, share positive), from the 1M
store directly (no engine replay — the fields are pure array
functions; the matrix and censuses compute them from their own bars
via the same functions). No luck budget here — an organ states
vocabulary, its consumers price their own fields. Twin-run pinned
(tests/test_organs.py). Weekly under Part C.
"""

import argparse
import json
import os
import subprocess
import sys

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

from backtest.sessions import sessions_of_index

OUT = os.path.join(ROOT, "reports", "scoreboard")
SV_WINDOW_BARS = 15     # one signal-TF window (15M) in 1M bars — the
                        # stack's registered TF as the unit, no new number


def sv_bar(opens, closes, volumes):
    """Close-direction signed volume per bar (doji = 0)."""
    return np.sign(np.asarray(closes, float)
                   - np.asarray(opens, float)) * np.asarray(volumes,
                                                            float)


def sv15(opens, closes, volumes, window=SV_WINDOW_BARS):
    """Trailing one-signal-TF-window signed-volume sum (includes the
    current bar; the first window-1 bars carry the partial sum)."""
    s = sv_bar(opens, closes, volumes)
    c = np.cumsum(s)
    out = c.copy()
    out[window:] = c[window:] - c[:-window]
    return out


def sv_session(opens, closes, volumes, ts):
    """Session-to-date signed-volume sum, reset at each new UTC trading
    day (stated convention, FLAGGED vs the store-native ldate)."""
    s = sv_bar(opens, closes, volumes)
    days = np.asarray(ts, "int64") // 86_400_000_000_000
    out = np.empty(len(s))
    run = 0.0
    prev = None
    for i in range(len(s)):
        if days[i] != prev:
            run = 0.0
            prev = days[i]
        run += s[i]
        out[i] = run
    return out


def _dist(v):
    v = v[~np.isnan(v)]
    if not len(v):
        return None
    return {"n": int(len(v)), "median": round(float(np.median(v)), 1),
            "p10": round(float(np.percentile(v, 10)), 1),
            "p90": round(float(np.percentile(v, 90)), 1),
            "share_positive": round(float(np.mean(v > 0)), 3)}


def run_instrument(instr, boundary_ns, golive_ns):
    df = pd.read_csv(os.path.join(ROOT, "clean_finsa",
                                  f"{instr}_1min.csv"),
                     usecols=["time", "open", "close", "volume"],
                     parse_dates=["time"])
    ts = df["time"].dt.as_unit("ns").astype("int64").to_numpy()
    a15 = sv15(df["open"].to_numpy(), df["close"].to_numpy(),
               df["volume"].to_numpy())
    asess = sv_session(df["open"].to_numpy(), df["close"].to_numpy(),
                       df["volume"].to_numpy(), ts)
    sess = np.array(sessions_of_index(
        pd.DatetimeIndex(df["time"])), dtype=object)
    wmask = {"backtest": ts < boundary_ns, "forward": ts >= golive_ns}
    out = {"instrument": instr, "n_bars": int(len(ts)), "cells": {}}
    for w, m in wmask.items():
        for s in sorted(set(sess.tolist())):
            sel = m & (sess == s)
            out["cells"][f"{w}|{s}"] = {
                "sv15": _dist(a15[sel]), "sv_sess": _dist(asess[sel])}
    return out


def _emit(art, head):
    L = ["# Organ #4 — Cumulative Signed Volume (GENERATED by "
         "backtest.signed_volume)", "",
         "Terms: [docs/GLOSSARY.md](../../docs/GLOSSARY.md).", "",
         f"Engine `{head[:9]}` — OBSERVATIONAL ORGAN (register 119; "
         "prereg_organ_signed_volume; register-16 family). VOCABULARY, "
         "not a signal: per-bar close-direction signed volume — sv15 "
         f"(trailing {SV_WINDOW_BARS} x 1M bars, the signal-TF window) "
         "and sv_sess (session-to-date, UTC-day reset — FLAGGED vs the "
         "native ldate session). Customers: H12's clauses (future "
         "operator proposal), the conditioning matrix (sv_sess sign "
         "dimension — field size restated there), arrival-anatomy "
         "(a)/(b). No luck budget here: consumers price their own "
         "fields. Distributions below are the vocabulary's range, not "
         "findings.", ""]
    for res in art["results"]:
        L += [f"## {res['instrument']} ({res['n_bars']} 1M bars)", "",
              "| window | session | sv15 med [p10..p90] | sv15 +share "
              "| sv_sess med [p10..p90] | sv_sess +share | n |",
              "|---|---|---|---|---|---|---|"]
        for key, c in res["cells"].items():
            w, s = key.split("|")
            a, b = c["sv15"], c["sv_sess"]
            if not a or not b:
                continue
            L.append(f"| {w} | {s} | {a['median']:g} [{a['p10']:g}"
                     f"..{a['p90']:g}] | {100 * a['share_positive']:.0f}% "
                     f"| {b['median']:g} [{b['p10']:g}..{b['p90']:g}] "
                     f"| {100 * b['share_positive']:.0f}% | {a['n']} |")
        L.append("")
    with open(os.path.join(OUT, "signed_volume.md"), "w") as f:
        f.write("\n".join(L))


def main():
    from engine.store_loader import lockbox_boundary, zones
    ap = argparse.ArgumentParser()
    ap.add_argument("--instr", nargs="*",
                    default=["uk100fut", "ger40fut", "nas100fut",
                             "us30fut"])
    a = ap.parse_args()
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT,
                          capture_output=True, text=True).stdout.strip()
    b, g = lockbox_boundary().value, zones()["go_live"].value
    results = [run_instrument(i, b, g) for i in a.instr]
    art = {"STAMP": ("OBSERVATIONAL organ #4 — signed-volume "
                     "vocabulary; consumers price their own fields; "
                     "never validation"),
           "engine_commit": head, "window_bars": SV_WINDOW_BARS,
           "results": results}
    with open(os.path.join(OUT, "signed_volume.json"), "w") as f:
        json.dump(art, f, indent=2, default=str)
    _emit(art, head)
    print(f"OBSERVATIONAL organ #4 -> {OUT}/signed_volume.md")


if __name__ == "__main__":
    main()
