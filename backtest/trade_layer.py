"""The narrative trade layer (register 76; pre-registered
prereg_trade_layer). Runs the composite sentences H17/H18/H19 (+ all
signal-live directional anchors for comparison) under R-OP2 across all
instruments, both windows, and emits the operator's working files:

  reports/trades.csv          — the trade journal: open/close ts +
    prices, direction, sentence ID, session, points, and six context
    tags at the fire bar (with-trend; new HH/HL/LH/LL per the engine's
    confirmed swing registry — trailing-confirmed, no lookahead; retest
    of a registered level within the ratified proximity band).
  reports/weekly_summary.csv  — per sentence per ISO week: trades,
    winners, losers, points won, points lost, net, plus running totals.

MANAGEMENT LADDER v2 (register 77): every journal row carries a
variant — the v0.3 incumbent R-OP2 plus R-BE / R-ARM15 / R-NOTRAIL —
and reports/management_grades.csv grades each variant x signal on the
doctrine axes (median-per-trade in ATR units, floor clearance beyond
the matched baseline ensemble's FULL member range, weekly-consistency
count). THE MISSING CONTROL, MANDATORY (register 77 clause 3): the
baseline ensembles run under the IDENTICAL management scheme per
variant; NO VARIANT'S NET IS QUOTABLE without its vs-baseline line
(hold-to-EOD numbers are suspected trend-exposure until it prints).
RE-FIRE DEDUP (register 77 clause 4): same sentence, same direction,
within REFIRE_DEDUP_BARS = one trade (derivation: the sequel window —
the scale that admits repeated sequels of one anchor episode;
RATIFIED at the 2026-08-28 sitting, register 88). Honest-fills rule 5 (register 77)
removes the instant-kill class at the fill-logic level.

FILL MODEL: PESSIMISTIC (register 65; ladder family). Entries UNREFINED
(register 70: refinement is per-family; this layer's choice, stated).
CONTEXT-TAG ANALYSIS IS POST-HOC EXPLORATORY (register 76 clause 5):
tags are reported with counts; no gates are minted from them without
the front door. Sealed/lockbox excluded; PROVISIONAL instruments carry
their stamps in the CSV's status column; twin-run pinned via the
underlying simulate(). Regenerated by every Part C run.

LOCKBOX-SPAN RULING (register 85, 2026-08-27): trades OPENING inside
the legacy lockbox span are excluded from every evidential aggregate
project-wide — the span is its own zone, neither backtest nor forward,
spendable only by a future dated ruling. trades.csv stays the COMPLETE
row-level journal (the audit trail; the enriched CSV carries
in_lockbox_span); weekly_summary.csv, management_grades.csv, and the
journal_baselines floors are EX-LOCKBOX, each stating the exclusion in
a leading '#' header line with reconciled row counts (readers:
pd.read_csv(..., comment='#')).
"""

